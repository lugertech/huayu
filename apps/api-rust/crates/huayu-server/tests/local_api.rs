async fn websocket_event(
    socket: &mut WebSocketStream<MaybeTlsStream<tokio::net::TcpStream>>,
) -> Value {
    tokio::time::timeout(std::time::Duration::from_secs(5), async {
        loop {
            match socket
                .next()
                .await
                .expect("WebSocket remains connected until the event")
                .expect("valid WebSocket frame")
            {
                Message::Text(text) => {
                    return serde_json::from_str(&text).expect("WebSocket event is JSON");
                }
                Message::Ping(payload) => socket
                    .send(Message::Pong(payload))
                    .await
                    .expect("test client answers heartbeat"),
                message => panic!("expected a JSON event, received {message:?}"),
            }
        }
    })
    .await
    .expect("WebSocket event arrives within the test timeout")
}

