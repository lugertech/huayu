export function useAssetTranslations() {
  const { locale, t } = useTranslations();
  const at = useCallback(
    (key: keyof (typeof assetMessages)["zh-CN"], values?: Values) =>
      translate(assetMessages, locale, key, values),
    [locale],
  );
  return { locale, t, at };
}
